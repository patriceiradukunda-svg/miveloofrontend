export const ADMIN_NAV: ReadonlyArray<{ href: string; label: string; group: string }> = PAGES.filter((p) => p.area === 'admin');

const dedupe = <T extends { href: string }>(xs: T[]): T[] => { const seen = new Set<string>(); return xs.filter((x) => (seen.has(x.href) ? false : (seen.add(x.href), true))); };
const hasModule = (mods: readonly string[], href: string) =>
  mods.some((m) => { const p = m.startsWith('/') ? m : href.startsWith('/admin/') ? '/admin/' + m : '/' + m; return href === p || href.startsWith(p + '/'); });
const areasOf = (position: string): string[] => {
  const k = position.split('-')[0] ?? '';
  return k === 'admin' ? ['admin', 'ai-ops'] : k === 'coop' ? ['group'] : k === 'inst' ? ['institution', 'intelligence'] : [k];
};

/** Sidebar links for a position. Positions without an entry (or normal accounts) keep the standard role menu. */
export function navForPosition<T extends { href: string }>(position: string | undefined | null, base: T[]): T[] {
  if (!position) return base;
  const mods = POSITION_MODULES[position];
  if (!mods) return base;
  const areas = areasOf(position);
  const pool = PAGES.filter((p) => areas.includes(p.area));
  const mine = (mods.includes('*') ? pool : pool.filter((p) => (COMMON.includes(p.href.split('/').pop() ?? '') && p.area === areas[0]) || hasModule(mods, p.href))) as unknown as T[];
  if (position.startsWith('admin-')) return dedupe([...mine, ...base.filter((l) => positionAllows(position, l.href))]);
  const shared = base.filter((l) => l.href.startsWith('/app/')).map((l) => ({ ...l, group: 'For everyone' }) as T);
  return dedupe([...mine, ...shared]);
}
